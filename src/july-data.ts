import type {
  ContentType,
  Country,
  Platform,
  ReportRow,
} from "./report-data";

const MONTH_KEY = "2026-07";

type RawJulyRow = {
  country: Country;
  platform: Platform;
  contentType: ContentType;
  slug: string;
  sourceName: string;
  title: string;
  date: string;
  spendEur: number;
  reach?: number;
  cpmEur?: number;
  frequency?: number;
  linkClicks?: number;
  cpcEur?: number;
  ctrPct?: number;
  engagements?: number;
  landingPageViews?: number;
  optimizationMismatch?: boolean;
};

const thumbnailFolder = {
  article: "articles",
  video: "video",
  post: "posts",
  reel: "reels",
} satisfies Record<ContentType, string>;

function normalizeDate(value: string) {
  const [day, month, year] = value.split("/");
  return `${day}.${month}.${year}`;
}

function row(input: RawJulyRow): ReportRow {
  const isLandingPageView = input.landingPageViews !== undefined;
  const results = isLandingPageView
    ? input.landingPageViews ?? null
    : input.engagements ?? null;
  const costPerResult =
    results && results > 0 ? input.spendEur / results : null;

  return {
    id: `${MONTH_KEY}-${input.country.toLowerCase()}-${input.platform}-${input.contentType}-${input.slug}`,
    country: input.country,
    platform: input.platform,
    contentType: input.contentType,
    sourceName: input.sourceName,
    title: input.title,
    date: normalizeDate(input.date),
    month_key: MONTH_KEY,
    spendEur: input.spendEur,
    reach: input.reach ?? null,
    frequency: input.frequency ?? null,
    cpmEur: input.cpmEur ?? null,
    linkClicks: input.linkClicks ?? null,
    cpcEur: input.cpcEur ?? null,
    ctrPct: input.ctrPct ?? null,
    resultType: isLandingPageView ? "landing_page_view" : "post_engagement",
    results,
    costPerResultEur: costPerResult,
    engagements: isLandingPageView ? null : input.engagements ?? null,
    cpeEur: isLandingPageView ? null : costPerResult,
    landingPageViews: input.landingPageViews ?? null,
    costPerLandingPageViewEur: isLandingPageView ? costPerResult : null,
    optimizationMismatch: input.optimizationMismatch,
    rankingEligible:
      !input.optimizationMismatch && results !== null && results > 0,
    thumbnail: `/thumbnails/${MONTH_KEY}/${input.country.toLowerCase()}/${input.platform}/${thumbnailFolder[input.contentType]}/${input.slug}.png`,
  };
}

